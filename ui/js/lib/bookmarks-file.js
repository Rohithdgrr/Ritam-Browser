/**
 * Netscape bookmark file import/export.
 * Pure string code, no DOM — unit-tested with node:test.
 * Import accepts the HTML format Chrome/Firefox/Edge export; export writes the
 * same format so bookmarks move between browsers in both directions.
 */

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" };

function decodeEntities(s) {
  return String(s).replace(/&(amp|lt|gt|quot|#39);/g, (_, e) => ENTITIES[e]);
}

function stripTags(s) {
  return String(s).replace(/<[^>]*>/g, '');
}

const isHttpUrl = (u) => /^https?:\/\//i.test(u);

/** Parse bookmark <a> entries out of an exported bookmarks HTML file. */
export function parseBookmarksHtml(html) {
  const out = [];
  const re = /<a\s[^>]*?href\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))[^>]*>([\s\S]*?)<\/a>/gi;
  let m;
  while ((m = re.exec(String(html ?? '')))) {
    const url = decodeEntities((m[1] ?? m[2] ?? m[3] ?? '').trim());
    if (!isHttpUrl(url)) continue;
    const title = decodeEntities(stripTags(m[4] ?? '').trim());
    out.push({
      title: title.slice(0, 200),
      url: url.slice(0, 2048),
    });
  }
  // Dedupe by URL, first occurrence wins.
  const seen = new Set();
  return out.filter(({ url }) => (seen.has(url) ? false : seen.add(url)));
}

/** Build a Netscape bookmark file (importable by every browser). */
export function buildBookmarksHtml(bookmarks) {
  const esc = (s) =>
    String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  const items = (bookmarks ?? []).filter((b) => isHttpUrl(b.url));
  const rows = items
    .map((b) => `    <DT><A HREF="${esc(b.url)}">${esc(b.title || b.url)}</A>`)
    .join('\n');
  return `<!DOCTYPE NETSCAPE-Bookmark-file-1>
<!-- Generated by Ritam Browser -->
<META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=UTF-8">
<TITLE>Bookmarks</TITLE>
<H1>Bookmarks</H1>
<DL><p>
${rows}
</DL><p>
`;
}
